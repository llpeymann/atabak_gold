/**
 * Phase 9 — identifiers for the Sales Engine (§7.2).
 *
 * Two very different identifiers live here, and mixing them up would be a security bug:
 *
 *  * `reference` (`SL-XXXXXXXX`) is the **customer-facing tracking code**. It is random, contains no
 *    personal data, and is deliberately *not* an authorization token: seeing a reference does not let
 *    anybody read a lead — a customer always comes back through their own platform identity (§10.4).
 *  * `submissionKey` / `draftId` are internal idempotency identifiers: the submission key is what
 *    makes a repeated confirmation click resolve to the *same* lead instead of creating a second one.
 */

import { randomInt, randomUUID } from 'node:crypto';

/** Alphabet without visually ambiguous characters (`0/O`, `1/I/L`) — it is read aloud over the phone. */
const REFERENCE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
const REFERENCE_BODY_LENGTH = 8;
const REFERENCE_PREFIX = 'SL-';

/** Internal `lead_<n>` ids are generated by the store; the sequence lives in the document. */
export function isLeadReference(value: unknown): value is string {
  if (typeof value !== 'string' || !value.startsWith(REFERENCE_PREFIX)) {
    return false;
  }

  const body = value.slice(REFERENCE_PREFIX.length);

  if (body.length !== REFERENCE_BODY_LENGTH) {
    return false;
  }

  return [...body].every((character) => REFERENCE_ALPHABET.includes(character));
}

/**
 * Generate a candidate reference.
 *
 * Uniqueness is *enforced by the store* inside the write transaction (the document keeps a reference
 * index); this function only produces an unguessable candidate, and the caller retries on collision.
 */
export function generateLeadReference(): string {
  let body = '';

  for (let index = 0; index < REFERENCE_BODY_LENGTH; index += 1) {
    body += REFERENCE_ALPHABET[randomInt(REFERENCE_ALPHABET.length)];
  }

  return `${REFERENCE_PREFIX}${body}`;
}

/** Internal idempotency key for one form submission (durable, carried by the confirmation button). */
export function generateSubmissionKey(): string {
  return `sub_${randomUUID().replace(/-/gu, '').slice(0, 24)}`;
}

/** Short-lived session id of an in-progress form; the buttons carry only this id. */
export function generateDraftId(): string {
  return `draft_${randomUUID().replace(/-/gu, '').slice(0, 16)}`;
}
